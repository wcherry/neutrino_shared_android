// Regenerates neutrino-core/src/test/resources/chunked_stream_vectors.json with real libsodium.
// Run from a directory with libsodium-wrappers@0.7.15 installed (crosscheck-web-crypto.sh makes one):
//   node generate-chunked-stream-vectors.mjs > chunked_stream_vectors.json
import _sodium from 'libsodium-wrappers';
await _sodium.ready; const s = _sodium;
const b64 = (u) => s.to_base64(u, s.base64_variants.URLSAFE_NO_PADDING);
const key = s.randombytes_buf(32);
function make(plain, chunk, rekeyAt) {
  const { state, header } = s.crypto_secretstream_xchacha20poly1305_init_push(key);
  const parts = [header];
  for (let off = 0, i = 0; ; off += chunk, i++) {
    const end = Math.min(off + chunk, plain.length);
    const last = end >= plain.length;
    let tag = last ? s.crypto_secretstream_xchacha20poly1305_TAG_FINAL : s.crypto_secretstream_xchacha20poly1305_TAG_MESSAGE;
    if (!last && rekeyAt === i) tag = s.crypto_secretstream_xchacha20poly1305_TAG_REKEY;
    parts.push(s.crypto_secretstream_xchacha20poly1305_push(state, plain.subarray(off, end), null, tag));
    if (last) break;
  }
  const total = parts.reduce((n, p) => n + p.length, 0); const out = new Uint8Array(total); let o = 0;
  for (const p of parts) { out.set(p, o); o += p.length; }
  return out;
}
const plain = new Uint8Array(1000); for (let i = 0; i < plain.length; i++) plain[i] = (i * 7 + 3) & 0xff;
const exact = plain.subarray(0, 768);
console.log(JSON.stringify({
  note: "Generated by libsodium-wrappers 0.7.15 (scripts/generate-chunked-stream-vectors.mjs). Plaintext byte i = (i*7+3)&0xff.",
  key: b64(key),
  cases: [
    { name: "1000 bytes in 256-byte chunks", chunkSize: 256, length: 1000, data: b64(make(plain, 256, -1)) },
    { name: "768 bytes, an exact multiple", chunkSize: 256, length: 768, data: b64(make(exact, 256, -1)) },
    { name: "1000 bytes, REKEY after chunk 1", chunkSize: 256, length: 1000, data: b64(make(plain, 256, 1)) },
    { name: "one chunk larger than the data", chunkSize: 4096, length: 1000, data: b64(make(plain, 4096, -1)) },
  ],
}, null, 1));
